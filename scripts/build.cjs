const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const core = fs.readFileSync(path.join(root, 'lib/counter.js'), 'utf8');
const source = fs.readFileSync(path.join(root, 'src/main.js'), 'utf8');
const license = fs.readFileSync(path.join(root, 'LICENSE'), 'utf8').trim();
const marker = 'require("../lib/counter")';
if (source.split(marker).length !== 2) throw new Error('Expected one counter import');
const bundle = source.replace(marker, () => `(function () {\nconst module = { exports: {} };\n${core}\nreturn module.exports;\n})()`);
fs.writeFileSync(path.join(root, 'main.js'), `/*!\n${license}\n*/\n// Generated by npm run build. Edit src/main.js and lib/counter.js.\n` + bundle);
console.log('Built main.js (Obsidian and CodeMirror are supplied by the host).');
